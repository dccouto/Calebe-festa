ALTER SESSION SET CURRENT_SCHEMA = CALEBEF;

CREATE TABLE usuarios_admin (
  id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email         VARCHAR2(320) NOT NULL,
  senha_hash    VARCHAR2(255) NOT NULL,
  nome          VARCHAR2(120),
  ativo         NUMBER(1) DEFAULT 1 NOT NULL CHECK (ativo IN (0,1)),
  criado_em     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  atualizado_em TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT usuarios_admin_email_uk UNIQUE (email)
);

CREATE TABLE sessao_token (
  id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id    NUMBER NOT NULL REFERENCES usuarios_admin(id) ON DELETE CASCADE,
  token_hash    VARCHAR2(128) NOT NULL,
  expira_em     TIMESTAMP WITH TIME ZONE NOT NULL,
  criado_em     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT sessao_token_hash_uk UNIQUE (token_hash)
);

CREATE INDEX sessao_token_usuario_idx ON sessao_token (usuario_id);
CREATE INDEX sessao_token_expira_idx ON sessao_token (expira_em);

CREATE TABLE rsvp_envio (
  id               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- Opcionais/legado (Oracle trata '' como NULL — não use NOT NULL aqui)
  responsavel_nome VARCHAR2(120),
  telefone         VARCHAR2(40),
  criado_em        TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE rsvp_convidado (
  id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  envio_id       NUMBER NOT NULL REFERENCES rsvp_envio(id) ON DELETE CASCADE,
  convidado_nome VARCHAR2(120) NOT NULL,
  status         VARCHAR2(20) NOT NULL CHECK (status IN ('confirmado', 'nao_pode')),
  criado_em      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX rsvp_convidado_envio_idx ON rsvp_convidado (envio_id);
CREATE INDEX rsvp_convidado_status_idx ON rsvp_convidado (status);

COMMIT;
